def _ensure_min(msgs: list[dict], filler_j: str, filler_s: str) -> list[dict]:
    while len(msgs) < MIN_MESSAGES:
        msgs.append({"senderRole": "junior", "text": filler_j})
        msgs.append({"senderRole": "senior", "text": filler_s})
    return msgs


def _food_chat(school: str, idx: int) -> dict:
    places = SCHOOL_FOOD[school]
    place, area, menu, price, wait, address = places[(idx - 1) % len(places)]
    msgs: list[dict] = []

    def j(t: str) -> None:
        msgs.append({"senderRole": "junior", "text": t})

    def s(t: str) -> None:
        msgs.append({"senderRole": "senior", "text": t})

    j(f"{school} 다니는데, {area} 쪽에서 실제로 있는 맛집 추천해 주세요. 줄 긴 데는 피하고 싶어요.")
